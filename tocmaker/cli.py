"""Command line: ``toc render spec.yaml -o out/`` and friends."""
from __future__ import annotations

import argparse
import json
import os
import sys

from . import __version__


def cmd_render(a):
    from .export import pptx_preview, svg_to_pdf, svg_to_png, svg_to_tiff
    from .layout import build_scene
    from .presets import find_preset as get_preset
    from .qa import format_report, run_qa
    from .render_pptx import render_pptx
    from .render_svg import render_svg
    from .spec import TocSpec

    spec = TocSpec.load(a.spec)
    if a.journal:
        spec.journal = a.journal
    preset = get_preset(spec.journal)
    scene, lay = build_scene(spec, preset)
    svg = render_svg(scene, preset)
    out = a.out or os.path.splitext(a.spec)[0] + "_out"
    os.makedirs(out, exist_ok=True)
    base = os.path.join(out, a.name)
    with open(base + ".svg", "w", encoding="utf-8") as fh:
        fh.write(svg)
    png = svg_to_png(svg, base + ".png", preset, a.dpi)
    svg_to_pdf(svg, base + ".pdf")
    if a.tiff:
        svg_to_tiff(svg, base + ".tif", preset, a.dpi)
    pptx_warn = []
    if not a.no_pptx:
        with open(a.spec, "r", encoding="utf-8") as fh:
            notes = "Generated by tocmaker from spec:\n" + fh.read()
        pptx_warn = render_pptx(scene, preset, base + ".pptx", scale=a.pptx_scale, icon_format=a.icon_format, notes=notes)
        if a.preview:
            pptx_preview(base + ".pptx", base + "_pptx_preview.png", dpi=min(a.dpi, 300))
    report = run_qa(spec, scene, lay, preset, svg, png)
    for w in pptx_warn:
        report["issues"].append(dict(level="warn", code="pptx", message=w))
    with open(base + "_qa.json", "w", encoding="utf-8") as fh:
        json.dump(report, fh, ensure_ascii=False, indent=2, default=str)
    print(format_report(report))
    print(f"wrote {base}.svg, .png ({a.dpi} dpi), .pdf" + ("" if a.no_pptx else ", .pptx") + (", .tif" if a.tiff else ""))
    return 1 if report["status"] == "fail" and a.strict else 0


def cmd_icons(a):
    from . import icons
    if a.action == "search":
        hits = icons.search(" ".join(a.query), limit=a.limit, sources=a.source or None)
        if not hits:
            print("no icons found")
        for h in hits:
            print(f"{h.id:60s} {h.license:12s} {h.author[:18]:18s} {', '.join(h.keywords[:6])}")
    elif a.action == "list":
        idx = icons.build_index()
        by = {}
        for i in idx:
            by.setdefault(i.source, 0)
            by[i.source] += 1
        for k, v in sorted(by.items()):
            print(f"{k:14s} {v}")
        print(f"total {len(idx)}")
    elif a.action == "sheet":
        from .sheet import contact_sheet
        hits = icons.search(" ".join(a.query), limit=a.limit, sources=a.source or None) if a.query else icons.build_index()
        path = contact_sheet(hits, a.out or "icons_sheet.png")
        print(f"wrote {path}")
    return 0


def cmd_presets(a):
    from .presets import list_presets
    for p in list_presets(include_db=a.all):
        print(f"{p['key']:28s} {p['width_mm']:6.1f} x {p['height_mm']:5.1f} mm  ratio {p['width_mm']/p['height_mm']:.2f}  "
              f"font {p['min_font_pt']}-{p['pref_font_pt']} pt  words<={p['max_words']}  {p['journal']}")
    return 0


def cmd_init(a):
    from .templates_lib import example_spec
    txt = example_spec(a.template, a.journal)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(txt)
        print(f"wrote {a.out}")
    else:
        print(txt)
    return 0


def cmd_vectorize(a):
    from .presets import find_preset
    from .vectorize import TraceOptions, vectorize
    opt = TraceOptions(colormode=a.mode, hierarchical=a.hierarchy, filter_speckle=a.speckle,
                       color_precision=a.color_precision, layer_difference=a.layer_difference,
                       max_shapes=a.max_shapes, flatten_tol=a.tolerance, drop_background=not a.keep_background)
    preset = find_preset(a.journal) if a.journal else None
    info = vectorize(a.image, a.out or os.path.splitext(a.image)[0] + "_vec", a.name, preset, a.width_mm, opt, a.preview,
                     text_mode=a.text)
    for k, v in info.items():
        print(f"{k}: {v}")
    return 0


def cmd_harvest(a):
    from .harvest import main as harvest_main
    return harvest_main(a)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="toc", description="tocmaker: journal TOC graphics from a YAML spec")
    ap.add_argument("--version", action="version", version=__version__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    r = sub.add_parser("render", help="render spec -> svg/png/pdf/pptx + QA")
    r.add_argument("spec")
    r.add_argument("-o", "--out", help="output directory (default: <spec>_out)")
    r.add_argument("-n", "--name", default="toc", help="output base name")
    r.add_argument("--journal", help="override journal preset")
    r.add_argument("--dpi", type=int, default=300)
    r.add_argument("--tiff", action="store_true", help="also write LZW TIFF")
    r.add_argument("--no-pptx", action="store_true")
    r.add_argument("--pptx-scale", type=float, default=1.0, help="scale the slide (1 = true TOC size)")
    r.add_argument("--icon-format", choices=["svg", "emf"], default="svg", help="icon embedding in PPTX")
    r.add_argument("--preview", action="store_true", help="render the PPTX with LibreOffice for a fidelity check")
    r.add_argument("--strict", action="store_true", help="exit 1 when QA fails")
    r.set_defaults(func=cmd_render)

    i = sub.add_parser("icons", help="search / list the icon library")
    i.add_argument("action", choices=["search", "list", "sheet"])
    i.add_argument("query", nargs="*")
    i.add_argument("--limit", type=int, default=15)
    i.add_argument("--source", action="append", help="envtox | healthicons | bioicons")
    i.add_argument("--out")
    i.set_defaults(func=cmd_icons)

    p = sub.add_parser("presets", help="list journal presets")
    p.add_argument("--all", action="store_true", help="include every journal from db/journal_specs.yaml")
    p.set_defaults(func=cmd_presets)

    n = sub.add_parser("init", help="write an example spec for a template")
    n.add_argument("--template", default="flow")
    n.add_argument("--journal", default="acs")
    n.add_argument("-o", "--out")
    n.set_defaults(func=cmd_init)

    v = sub.add_parser("vectorize", help="trace a finished raster TOC image into SVG + native PPTX shapes")
    v.add_argument("image", help="PNG/JPG/TIF (or SVG, which is rasterised first)")
    v.add_argument("-o", "--out")
    v.add_argument("-n", "--name", default="traced")
    v.add_argument("--journal", help="set the physical width from a journal preset (e.g. acs)")
    v.add_argument("--width-mm", type=float, help="physical width of the output (default: 300 dpi of the pixels)")
    v.add_argument("--mode", choices=["color", "binary"], default="color")
    v.add_argument("--hierarchy", choices=["cutout", "stacked"], default="cutout",
                   help="cutout: non-overlapping regions (editable); stacked: painter's layers (more faithful on soft edges)")
    v.add_argument("--speckle", type=int, default=6, help="drop regions smaller than N px")
    v.add_argument("--color-precision", type=int, default=6, help="colour bits kept (lower = fewer colours)")
    v.add_argument("--layer-difference", type=int, default=24)
    v.add_argument("--max-shapes", type=int, default=1500)
    v.add_argument("--tolerance", type=float, default=0.6, help="curve flattening tolerance, px")
    v.add_argument("--keep-background", action="store_true")
    v.add_argument("--preview", action="store_true", help="render the PPTX with LibreOffice")
    v.add_argument("--text", choices=["ocr", "trace", "none"], default="ocr",
                   help="ocr: lift text into editable text objects; trace: keep as shapes; none: erase")
    v.set_defaults(func=cmd_vectorize)

    h = sub.add_parser("harvest", help="download open-access graphical abstracts into the reference database")
    h.add_argument("--journal", action="append", help="journal name as in Europe PMC (repeatable)")
    h.add_argument("--query", help="free Europe PMC query (overrides --journal)")
    h.add_argument("--years", default="2022-2026")
    h.add_argument("--n", type=int, default=120, help="target number of images")
    h.add_argument("--out", default="tocmaker/db/reference")
    h.add_argument("--dry-run", action="store_true", help="only write metadata, do not download images")
    h.add_argument("--source", choices=["europepmc", "pubmed"], default="pubmed",
                   help="pubmed: NCBI E-utilities + Elsevier PII image pattern (default); europepmc: JATS XML graphical abstracts")
    h.add_argument("--seed", help="download images for a prepared seed index (db/reference/seed_index.csv built via the PubMed connector)")
    h.add_argument("--sleep", type=float, default=0.34)
    h.set_defaults(func=cmd_harvest)

    a = ap.parse_args(argv)
    return a.func(a)


if __name__ == "__main__":
    sys.exit(main())
